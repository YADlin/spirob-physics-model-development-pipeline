"""Experiment 4 - validation of this repository against the original work.

V1 Geometry. The same SpiRob is generated by this repository
   (``spirob.geometry``) and by the authors' Open-Spiral-Robots design tool;
   unit-by-unit chord lengths and widths are compared. The authors' code is
   NOT copied here (it is PolyForm-Noncommercial): its pure geometry
   functions are loaded at run time from a local clone, the same way the
   authors' own parity tests do, via ``--osr /path/to/Open-Spiral-Robots``
   or the OSR_REPO environment variable.
V2 Packed shape. The simulated fully curled body is compared with the
   analytic curled spiral of the generator.
V3 Lock forces. Simulated joint lock forces (Experiment 1) against the
   closed-form F_i = k_i Delta_theta / h_i.
V4 Joint limits. The generator writes hinge ranges of +/- pi; MuJoCo ignores
   parent-child contacts by default, so nothing stops adjacent units from
   passing through each other. The body is pulled with that setting.
"""
from __future__ import annotations

import ast
import json
import math
import os
from pathlib import Path
from typing import List, Tuple

import numpy as np

from spirob import geometry as g

from . import analytic, designs as D, model as M, sim
from .designs import STUDY

OUT = STUDY / "results" / "validation"


# ------------------------------------------------------------------ V1
def load_osr(osr_repo: Path) -> dict:
    src = (osr_repo / "design-tool" / "DesignTool.py").read_text(encoding="utf-8")
    want = {"_polar_to_cart", "_build_unfold_polygons"}
    body = [n for n in ast.parse(src).body if isinstance(n, ast.FunctionDef) and n.name in want]
    ns = {"math": math, "List": List, "Tuple": Tuple, "Point2D": Tuple[float, float]}
    exec(compile(ast.Module(body=body, type_ignores=[]), "DesignTool.py", "exec"), ns)
    return ns


def osr_units(ns: dict, a_mm: float, b: float, dtheta_deg: int, n_units: int):
    """Tip-first list of (chord_mm, width_mm) from the authors' unfold polygons."""
    prim, mirr = ns["_build_unfold_polygons"](a_mm, b, dtheta_deg, 0.5, 0.0, n_units)
    out = []
    for P, Q in zip(prim, mirr):
        P = np.array(P); Q = np.array(Q)
        chord = abs(P[2, 0] - P[3, 0])                      # q1 - q0 along the axis
        w0 = abs(P[0, 1] - Q[0, 1])                          # full width at the unit's tip-side ray
        w1 = abs(P[1, 1] - Q[1, 1])
        out.append((chord, w0, w1))
    return np.array(out)


def pipeline_units(design: D.Design):
    """Tip-first complete units from this repository's canonical geometry."""
    params = json.loads((D.BUILD_ROOT / f"{design.name}.params.json").read_text())
    geo = g.from_params(params)
    rows = []
    # straightened quads, tip first: slots [A0, A1, B1, B0]; A = central
    # spiral (the axis, along +y), B = inner edge. Full width = 2 |x_B|.
    for u, q in zip(geo.units_tip_to_base, geo.straight_quads()):
        if u.is_partial:
            continue
        q = q - q[0]
        chord = float(np.linalg.norm(q[1]))
        rows.append((chord * 1e3, 2 * abs(q[3, 0]) * 1e3, 2 * abs(q[2, 0]) * 1e3))
    return np.array(rows), geo


def geometry_crosscheck(osr_repo: Path) -> list[dict]:
    ns = load_osr(osr_repo)
    out = []
    for design in [*D.PAPER, analytic.osr_print_design()]:
        pu, geo = pipeline_units(design)
        b, a_mm = geo.spiral.b, geo.spiral.a_m * 1e3
        ou = osr_units(ns, a_mm, b, int(round(design.dtheta_deg)), len(pu))
        rel_chord = np.abs(ou[:, 0] - pu[:, 0]) / pu[:, 0]
        # widths: compare the larger end width (the pipeline's start/end
        # naming is tip/base specific, so compare max and min of each unit)
        pw = np.sort(pu[:, 1:], axis=1); owd = np.sort(ou[:, 1:], axis=1)
        rel_w = np.abs(owd - pw) / pw
        out.append(dict(design=design.name, phi_deg=design.phi_deg, b=b, a_mm=a_mm,
                        n_units_compared=len(pu),
                        max_rel_err_chord=float(rel_chord.max()),
                        max_rel_err_width=float(rel_w.max()),
                        pipeline_chords_mm=pu[:, 0].tolist(), osr_chords_mm=ou[:, 0].tolist(),
                        pipeline_width_mm=pw[:, 1].tolist(), osr_width_mm=owd[:, 1].tolist(),
                        sum_chords_pipeline_mm=float(pu[:, 0].sum()),
                        sum_chords_osr_mm=float(ou[:, 0].sum())))
    return out


# ------------------------------------------------------------------ V2
def packed_shape_error(design: D.Design) -> dict:
    z = np.load(STUDY / "results" / "curl" / f"{design.name}__cubic.npz")
    line_sim = z["line"][-1]                         # base -> tip, joints + tip
    sm = M.make(design, tag="validation")
    m, d = sm.load()
    import mujoco
    qi = sim.qpos_index(m, sm)
    d.qpos[qi] = -math.radians(design.dtheta_deg)   # same sign as the +X curl in Experiment 1
    mujoco.mj_kinematics(m, d)
    line_ideal = sim.centerline(m, d, sm)
    if np.linalg.norm(line_ideal[-1] - line_sim[-1]) > np.linalg.norm(line_ideal[-1] * [-1, 1] - line_sim[-1]):
        d.qpos[qi] *= -1
        mujoco.mj_kinematics(m, d)
        line_ideal = sim.centerline(m, d, sm)
    err = np.linalg.norm(line_sim - line_ideal, axis=1)
    return dict(design=design.name, rms_mm=float(np.sqrt(np.mean(err ** 2)) * 1e3),
                max_mm=float(err.max() * 1e3), tip_mm=float(err[-1] * 1e3),
                line_sim=line_sim.tolist(), line_ideal=line_ideal.tolist())


# ------------------------------------------------------------------ V3
def lock_force_agreement() -> list[dict]:
    out = []
    for r in json.loads((STUDY / "results" / "curl" / "summary.json").read_text()):
        if r["law"] != "cubic":
            continue
        s = np.array(r["lock_force_sim"]); a = np.array(r["lock_force_analytic"])
        ok = ~np.isnan(s)
        ok[0] = False      # base joint: the packed coil presses on the base link
        rel = np.abs(s[ok] - a[ok]) / a[ok]
        out.append(dict(design=r["design"], median_rel_err=float(np.median(rel)),
                        max_rel_err=float(rel.max()), n=int(ok.sum())))
    return out


# ------------------------------------------------------------------ V4
def pipeline_limits_check(design: D.Design) -> dict:
    res = {}
    for limits in ("pipeline", "dtheta"):
        sm = M.make(design, limits=limits, f_max=200.0, tag=f"limits_{limits}")
        f = 1.25 * sim.f_pack_estimate(sm)
        log = sim.ramp_single_cable(sm, 1, f, t_ramp=4.0)
        q = np.abs(log["q"][-1]) / math.radians(design.dtheta_deg)
        res[limits] = dict(max_q_over_dtheta=float(q.max()), q_over_dtheta=q.tolist(),
                           line=log["line"][-1].tolist())
    return dict(design=design.name, **res)


def main(osr_repo: Path) -> dict:
    OUT.mkdir(parents=True, exist_ok=True)
    out = dict(
        geometry=geometry_crosscheck(osr_repo),
        packed=[packed_shape_error(d) for d in (D.CURRENT, *D.SWEEP, *D.PAPER, analytic.osr_print_design())],
        lock_forces=lock_force_agreement(),
        limits=pipeline_limits_check(D.CURRENT),
    )
    (OUT / "validation.json").write_text(json.dumps(out, indent=1))
    return out


